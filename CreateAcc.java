    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
  String username = jTextField1.getText().trim();
String password = new String(jPasswordField1.getPassword());
String confirm = new String(jPasswordField2.getPassword());

if (username.isEmpty() || password.isEmpty() || confirm.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill in all fields!");
    return;
}

if (username.contains(",") || username.contains("\n")
        || username.contains("\r")) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Invalid username!");
    return;
}

if (!password.equals(confirm)) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Passwords do not match!");
    return;
}

if (password.length() < 8) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Password must be at least 8 characters!");
    return;
}

if (jComboBox1.getSelectedItem() == null) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please select a role!");
    return;
}

try {
    String role = jComboBox1.getSelectedItem().toString();

    if (AccountCSV.usernameExists(username)) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Username already exists!");
        return;
    }

    if (role.equalsIgnoreCase("Administrator")
            && AccountCSV.adminExists()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Only one Administrator account is allowed!");
        return;
    }

    AccountCSV.createAccount(username, password, role);

    javax.swing.JOptionPane.showMessageDialog(this,
            "Account created successfully!");

    LOGIN login = new LOGIN();
    login.setLocationRelativeTo(null);
    login.setVisible(true);

    this.dispose();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error creating account: " + e.getMessage());
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton1ActionPerformed

